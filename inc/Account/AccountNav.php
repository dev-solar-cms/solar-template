	/**
	 * Builds the sidebar's navigation items from WooCommerce's own (theme-reordered) account menu.
	 *
	 * @return array<int, array{slug: string, label: string, url: string, icon: string, is_active: bool, is_logout: bool}>
	 */
	public static function items(): array {
		$icons = self::icons();
		$items = array();

		foreach ( wc_get_account_menu_items() as $endpoint => $label ) {
			$items[] = array(
				'slug'      => $endpoint,
				'label'     => $label,
				'url'       => wc_get_account_endpoint_url( $endpoint ),
				'icon'      => $icons[ $endpoint ] ?? '',
				'is_active' => str_contains( wc_get_account_menu_item_classes( $endpoint ), 'is-active' ),
				'is_logout' => 'customer-logout' === $endpoint,
			);
		}

		return $items;
	}
